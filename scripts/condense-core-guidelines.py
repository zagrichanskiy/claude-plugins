#!/usr/bin/env python3
"""Condense the C++ Core Guidelines into one file per section.

By default the script downloads CppCoreGuidelines.md at the commit pinned in the README and checks
its SHA-256. The download is kept in memory only. --source reads a local copy instead.

Each rule keeps its id, its title and its Reason text, or its lead text up to the first heading
when it has no Reason heading. Examples, notes, exceptions and enforcement text are dropped. A rule whose reason is missing, empty or only "???" is a stub and is dropped.
The output is deterministic: a rerun on the same input writes byte-identical files.
"""

import argparse
import hashlib
import pathlib
import re
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = ROOT / "plugins" / "cure" / "knowledge" / "cpp-core-guidelines"

SECTIONS = [
    "P", "I", "F", "C", "Enum", "R", "ES", "Per", "CP", "E", "Con", "T", "CPL", "SF", "SL", "A",
]

SECTION_HEADING = re.compile(r'^# <a name="[^"]*"></a>([A-Za-z]+): (.+)$')
RULE_HEADING = re.compile(r'^### <a name="[^"]*"></a>\s*([A-Za-z]+(?:\.[A-Za-z]+)*\.\d+\??): (.+)$')
ANY_HEADING = re.compile(r"^#{1,6} ")
REASON_HEADING = re.compile(r"^#{4,5} Reason\s*$")
INTERNAL_LINK = re.compile(r"\[([^\]]+)\]\(#[^)]*\)")
COMMIT = re.compile(r"^\| Commit \| ([0-9a-f]{40}) \|$", re.MULTILINE)
SHA256 = re.compile(r"^\| SHA-256 \| ([0-9a-f]{64}) \|$", re.MULTILINE)
URL = "https://raw.githubusercontent.com/isocpp/CppCoreGuidelines/{commit}/CppCoreGuidelines.md"


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=pathlib.Path,
                        help="local CppCoreGuidelines.md to read instead of downloading it")
    parser.add_argument("--out", type=pathlib.Path, default=BASE / "sections")
    parser.add_argument("--readme", type=pathlib.Path, default=BASE / "README.md")
    return parser.parse_args()


def split_sections(lines):
    """Return {section id: (title, body lines)} for every top-level section."""
    sections = {}
    current = None
    for line in lines:
        if line.startswith("# "):
            match = SECTION_HEADING.match(line)
            current = match.group(1) if match else None
            if current is not None:
                sections[current] = (match.group(2).strip(), [])
            continue
        if current is not None:
            sections[current][1].append(line)
    return sections


def split_rules(body):
    """Return [(rule id, title, body lines)] in source order."""
    rules = []
    current = None
    for line in body:
        match = RULE_HEADING.match(line)
        if match:
            current = (match.group(1), match.group(2).strip(), [])
            rules.append(current)
        elif line.startswith("## ") or line.startswith("### "):
            current = None
        elif current is not None:
            current[2].append(line)
    return rules


def block(lines, start):
    """Return the lines from start up to the next heading, with outer blank lines removed."""
    end = start
    while end < len(lines) and not ANY_HEADING.match(lines[end]):
        end += 1
    text = []
    for line in lines[start:end]:
        if line.strip() == "???":
            continue  # a placeholder paragraph carries no reason
        if not line.strip() and text and not text[-1].strip():
            continue
        text.append(line)
    while text and not text[0].strip():
        text.pop(0)
    while text and not text[-1].strip():
        text.pop()
    return text


def reason(body):
    """Return the Reason lines of a rule, or its lead text up to the first heading when it has none."""
    for index, line in enumerate(body):
        if REASON_HEADING.match(line):
            return block(body, index + 1)
    return block(body, 0)


def is_stub(text):
    return not "".join(text).replace("?", "").strip()


def clean(line):
    return INTERNAL_LINK.sub(r"\1", line.rstrip())


def render(section_id, title, commit, rules):
    out = [
        f"# {section_id} ({title})",
        "",
        f"Condensed from C++ Core Guidelines commit {commit}: rule id, title and reason only.",
        "Generated by scripts/condense-core-guidelines.py. Do not edit.",
    ]
    for rule_id, rule_title, text in rules:
        out += ["", f"## {rule_id}: {clean(rule_title)}", ""]
        out += [clean(line) for line in text]
    return "\n".join(out) + "\n"


def download(url):
    """Return the body of url, or exit with a message that names --source."""
    try:
        with urllib.request.urlopen(url, timeout=60) as response:
            return response.read()
    except (urllib.error.URLError, OSError) as error:
        sys.exit(f"cannot download {url}: {error}\n"
                 "Pass a local copy of CppCoreGuidelines.md with --source <path>.")


def main():
    args = parse_args()
    readme = args.readme.read_text(encoding="utf-8")
    match = COMMIT.search(readme)
    if not match:
        sys.exit(f"{args.readme}: no '| Commit | <sha> |' row")
    commit = match.group(1)
    match = SHA256.search(readme)
    if not match:
        sys.exit(f"{args.readme}: no '| SHA-256 | <hex> |' row")
    expected = match.group(1)

    if args.source is not None:
        origin = str(args.source)
        data = args.source.read_bytes()
    else:
        origin = URL.format(commit=commit)
        data = download(origin)
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected:
        sys.exit(f"{origin}: SHA-256 {actual} does not match {expected} in {args.readme}")

    lines = data.decode("utf-8").splitlines()
    sections = split_sections(lines)
    missing = [s for s in SECTIONS if s not in sections]
    if missing:
        sys.exit(f"{origin}: sections not found: {', '.join(missing)}")

    args.out.mkdir(parents=True, exist_ok=True)
    for section_id in SECTIONS:
        title, body = sections[section_id]
        kept, stubs = [], []
        for rule_id, rule_title, rule_body in split_rules(body):
            text = reason(rule_body)
            if is_stub(text):
                stubs.append(rule_id)
            else:
                kept.append((rule_id, rule_title, text))
        path = args.out / f"{section_id}.md"
        path.write_text(render(section_id, title, commit, kept), encoding="utf-8", newline="\n")
        print(f"{section_id}: {len(kept)} rules, {len(stubs)} stubs dropped"
              + (f" ({', '.join(stubs)})" if stubs else ""))


if __name__ == "__main__":
    main()
